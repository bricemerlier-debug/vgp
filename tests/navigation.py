from playwright.sync_api import sync_playwright, expect
import json
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 page=b.new_page()
 errors=[]
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto('http://127.0.0.1:8000')
 page.get_by_role('button',name='Ouvrir le menu',exact=True).click()
 assert page.locator('#menuToggle').get_attribute('aria-expanded')=='true'
 page.keyboard.press('Escape')
 expect(page.locator('#menuToggle')).to_have_attribute('aria-expanded','false')
 page.get_by_role('button',name='Ouvrir le menu',exact=True).click()
 page.get_by_role('button',name='Propriétaires',exact=True).click()
 assert page.locator('#ownersView').is_visible() and not page.locator('#materialView').is_visible()
 assert 'Sans propriétaire' in page.locator('#ownersList').inner_text()
 page.on('dialog',lambda d:d.accept('Entreprise A'))
 page.get_by_role('button',name='+ Ajouter un propriétaire',exact=True).click()
 assert 'Entreprise A' in page.locator('#ownersList').inner_text()
 card=page.locator('.owner-card').filter(has=page.get_by_role('heading',name='Entreprise A',exact=True))
 assert '0 équipement' in card.inner_text()
 card.get_by_role('button').click()
 assert page.locator('#ownerProfileName').inner_text()=='Entreprise A'
 expect(page.get_by_text('Aucun équipement associé à cette personne.',exact=True)).to_be_visible()
 page.get_by_role('button',name='Ouvrir le menu',exact=True).click()
 page.locator('[data-view=material]').click()
 page.get_by_role('button',name='+ Ajouter un équipement').click()
 form=page.locator('#equipmentForm')
 form.locator('[name=identifier]').fill('NAV-1')
 form.locator('[name=designation]').fill('Équipement propriétaire A')
 form.locator('[name=owner]').select_option('Entreprise A')
 form.get_by_role('button',name='Enregistrer l’équipement').click()
 assert page.locator('tbody tr').count()==3  # Creation intentionally returns to the complete list.
 page.get_by_role('button',name='Ouvrir le menu',exact=True).click()
 page.get_by_role('button',name='Propriétaires',exact=True).click()
 assert '1 équipement' in card.inner_text()
 card.get_by_role('button').click()
 page.locator('#ownerProfile').get_by_role('button',name='Ouvrir',exact=True).click()
 assert 'Entreprise A' in page.locator('#detailContent').inner_text()
 page.locator('#detail [data-close]').click()
 page.get_by_role('button',name='Ouvrir le menu',exact=True).click()
 page.locator('[data-view=material]').click()
 assert page.locator('tbody tr').count()==3
 assert page.locator('#ownerFilterBar').is_hidden()
 page.set_viewport_size({'width':390,'height':844})
 page.get_by_role('button',name='Ouvrir le menu',exact=True).click()
 page.get_by_role('button',name='Propriétaires',exact=True).click()
 assert page.locator('body').evaluate('(e)=>e.scrollWidth <= window.innerWidth')
 assert page.locator('#ownersTitle').evaluate('(e)=>e===document.activeElement')
 page.reload()
 page.get_by_role('button',name='Ouvrir le menu',exact=True).click()
 page.get_by_role('button',name='Propriétaires',exact=True).click()
 assert 'Entreprise A' in page.locator('#ownersList').inner_text()
 assert not errors,errors
 b.close()
 print('PASS: menu, fermeture clavier, propriétaires et compteurs, filtre exact, retour au matériel complet, mobile, persistance')
