import assert from 'node:assert/strict';
import {containerWeeklyAgenda,containerArchiveInfo,containerRecordsValid,containerMonthlyReport} from '../containers.mjs';
const preventive=date=>({number:date,date,type:'préventif',controller:'Atelier',generalState:'',comment:'',parts:{}});
const box=(id,subtype,dates)=>({id,number:id,type:'CE',subtype,interventions:dates.map(preventive)});
const archived={...box('ARCHIVE','PC',['2025-10-22']),manualArchive:{date:'2026-10-18',comment:'Hors service',by:'test@example.test',at:'2026-10-18T12:00:00Z'}};
const containers=[box('LUNDI','PC',['2025-10-19']),box('CARCASSE','Carcasse - PLAT',['2025-04-23']),box('DIMANCHE','PC',['2025-10-25']),box('SEMAINE-SUIVANTE','PC',['2025-10-26']),box('FAIT','PC',['2025-10-20','2026-10-20']),box('ANTICIPE','PC',['2025-10-23','2026-10-18']),box('INCONNU','PC',[]),archived];
const report=containerWeeklyAgenda(containers,'2026-10-21','2026-10-21');
assert.equal(report.start,'2026-10-19');assert.equal(report.end,'2026-10-25');
assert.equal(report.total,4);assert.equal(report.completed,1);assert.equal(report.pending,3);
assert.equal(report.days[4].entries[0].number,'CARCASSE');
assert.equal(report.days[1].entries[0].done,true);
assert.equal(report.days[6].entries[0].number,'DIMANCHE');
assert.equal(report.unknown,1);assert.equal(report.overdue,1);
assert.ok(!report.days.flatMap(d=>d.entries).some(e=>['ARCHIVE','ANTICIPE'].includes(e.number)));
assert.equal(containerWeeklyAgenda([box('FIN-MOIS','PC',['2024-02-29'])],'2025-02-28','2025-02-28').days[4].entries[0].due,'2025-02-28');
assert.equal(containerArchiveInfo(archived).manual,true);
assert.equal(containerArchiveInfo(archived).by,'test@example.test');
assert.ok(containerRecordsValid({containers}));
assert.equal(containerRecordsValid({containers:[{...archived,manualArchive:{date:'invalide'}}]}),false);
assert.equal(containerMonthlyReport([archived],2025,10).total,1);
console.log('Agenda : échéances 12/18 mois, semaines, reset anticipé, réalisés et rebut manuel OK.');
