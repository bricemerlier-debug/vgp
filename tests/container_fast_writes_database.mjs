import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {PGlite} from '@electric-sql/pglite';
import {freezeTracking} from '../domain.mjs';

const db=new PGlite();
await db.exec(`create role anon;create role authenticated;create schema auth;create table auth.users(id uuid primary key);create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;grant usage on schema public,auth to authenticated,anon;grant execute on function auth.uid() to authenticated;`);
for(const file of ['001_schema.sql','003_tracking_guard.sql','004_fast_writes.sql','015_container_fast_writes.sql','016_container_import_timeout.sql'])await db.exec(readFileSync('supabase/'+file,'utf8'));
const workspace='10000000-0000-0000-0000-000000000001',user='20000000-0000-0000-0000-000000000001';
await db.query('insert into auth.users values($1)',[user]);
await db.query('insert into public.workspaces values($1,$2)',[workspace,'Test isolé']);
await db.query('insert into public.workspace_members values($1,$2,$3)',[workspace,user,'admin']);
await db.query('insert into public.workspace_state(workspace_id) values($1)',[workspace]);
await db.query("select set_config('request.jwt.claim.sub',$1,false)",[user]);
await db.exec('set role authenticated');
const equipment={id:'e1',siteId:1,identifier:'VGP1',designation:'Exemple',months:12,controls:[],obligations:[]};
const initial=freezeTracking({owners:[],equipment:[equipment]},null,'2026-10-19','Testeur');
await db.query('select public.write_state($1,0,$2::jsonb,null)',[workspace,JSON.stringify(initial)]);
const container={id:'c1',number:'CE048',type:'CE',subtype:'R2 - VERTE',interventions:[{number:'22293',date:'2026-01-15',type:'préventif',controller:'Laurent B.',generalState:'',comment:'',parts:{}}]};
const write=async(revision,items)=>db.query('select public.write_containers($1,$2,$3::jsonb)',[workspace,revision,JSON.stringify(items)]);
await write(1,[container]);
const current=(await db.query('select public.read_state($1) as state',[workspace])).rows[0].state;
assert.equal(current.revision,2);
assert.deepEqual(current.payload.equipment,initial.equipment);
assert.deepEqual(current.payload.containers,[container]);
assert.equal((await db.query('select count(*) as n from public.state_history')).rows[0].n,2);
await assert.rejects(()=>write(2,[{...container,interventions:[]}]),/Historique d’intervention incomplet/);
await assert.rejects(()=>write(2,[container,{...container,id:'c2'}]),/Numéro de contenant dupliqué/);
await assert.rejects(()=>write(1,[container]),/REVISION_CONFLICT/);
assert.equal((await db.query('select revision from public.workspace_state')).rows[0].revision,2);
await db.exec('reset role');
await db.query('delete from public.workspace_members where workspace_id=$1 and user_id=$2',[workspace,user]);
await db.exec('set role authenticated');
await assert.rejects(()=>write(2,[container]),/Écriture refusée/);
await db.close();
console.log('Écriture ciblée : historique, révision, droits et données VGP préservés.');
