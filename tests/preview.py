from pathlib import Path
from playwright.sync_api import sync_playwright,expect
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 page=b.new_page();errors=[]
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto('http://127.0.0.1:8000')
 html=Path('prototype-vgp.html').read_text()
 page.evaluate('html=>{document.body.innerHTML="";const frame=document.createElement("iframe");frame.id="preview";frame.setAttribute("sandbox","allow-scripts allow-forms allow-modals allow-popups allow-downloads");frame.srcdoc=html;document.body.append(frame)}',html)
 frame=page.frame_locator('#preview')
 expect(frame.locator('#storageNotice')).to_be_visible()
 frame.get_by_role('button',name='+ Ajouter un équipement').click()
 form=frame.locator('#equipmentForm')
 form.locator('[name=identifier]').fill('APERÇU-1234')
 form.locator('[name=designation]').fill('Anneau test aperçu')
 form.get_by_role('button',name='Enregistrer l’équipement').click()
 expect(frame.locator('#editor')).not_to_be_visible()
 expect(frame.locator('tbody tr')).to_have_count(3)
 expect(frame.locator('#message')).to_contain_text('session uniquement')
 row=frame.locator('tbody tr').filter(has_text='APERÇU-1234')
 row.get_by_role('button',name='Ouvrir',exact=True).click()
 frame.get_by_role('button',name='+ Enregistrer un contrôle').click()
 form=frame.locator('#controlForm')
 form.locator('[name=intervenant]').fill('Testeur')
 form.locator('[name=result]').select_option('Bon état')
 form.get_by_role('button',name='Enregistrer le contrôle',exact=True).click()
 expect(frame.locator('#control')).not_to_be_visible()
 assert 'Bon état' in frame.locator('#detailContent').inner_text()
 with page.expect_download() as pdf:frame.get_by_role('button',name='Télécharger le PDF').click()
 pdf.value.save_as('/tmp/vgp-preview-control.pdf')
 frame.locator('#detail [data-close]').click()
 with page.expect_download() as backup:frame.get_by_role('button',name='Exporter une sauvegarde').click()
 backup.value.save_as('/tmp/vgp-preview-backup.json')
 assert not errors,errors
 b.close()
 print('PASS: aperçu sandbox sans accès localStorage, création visible, contrôle historique, PDF et export')
