from playwright.sync_api import sync_playwright,expect
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 page=b.new_page()
 errors=[]
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.route('**/cloud-config.js',lambda r:r.fulfill(body="window.VGP_CLOUD={enabled:false};",content_type='text/javascript'));page.goto('http://127.0.0.1:8000'+'#material')
 page.get_by_role('button',name='Ouvrir le menu',exact=True).click()
 page.locator('[data-view=kpi]').click()
 expect(page.locator('#kpiView')).to_be_visible()
 expect(page.locator('#materialView')).to_be_hidden()
 expect(page.locator('#kpi-performed')).to_have_text('1')
 expect(page.locator('#kpi-actions')).to_have_text('1')
 expect(page.locator('#kpi-todo')).to_have_text('1')
 expect(page.locator('#kpi-percent')).to_have_text('50 %')
 assert page.locator('#kpiTitle').evaluate('(e)=>e===document.activeElement')
 # A new control updates both the historical count and current coverage.
 page.get_by_role('button',name='Ouvrir le menu',exact=True).click()
 page.locator('[data-view=material]').click()
 page.get_by_role('button',name='Ouvrir',exact=True).last.click()
 page.get_by_role('button',name='+ Enregistrer un contrôle').click()
 form=page.locator('#controlForm')
 form.locator('[name=intervenant]').fill('Testeur')
 form.locator('[name=result]').select_option(label='Mauvais état — à jeter')
 form.get_by_role('button',name='Enregistrer le contrôle',exact=True).click()
 page.locator('#detail [data-close]').click()
 page.locator('#search').fill('aucun résultat')
 page.get_by_role('button',name='Ouvrir le menu',exact=True).click()
 page.locator('[data-view=kpi]').click()
 expect(page.locator('#kpi-performed')).to_have_text('2')
 expect(page.locator('#kpi-actions')).to_have_text('2')
 expect(page.locator('#kpi-todo')).to_have_text('1')
 expect(page.locator('#kpi-percent')).to_have_text('100 %')
 page.set_viewport_size({'width':390,'height':844})
 assert page.locator('body').evaluate('(e)=>e.scrollWidth <= window.innerWidth')
 assert not errors,errors
 b.close()
 print('PASS: navigation KPI, indicateurs, mise à jour après contrôle, indépendance du résultat et des filtres, mobile')
