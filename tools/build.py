from pathlib import Path
import argparse
parser=argparse.ArgumentParser()
parser.add_argument("--cloud",action="store_true",help="Inclure la configuration Supabase publique dans le HTML autonome")
args=parser.parse_args()
root=Path(__file__).resolve().parents[1]
html=(root/'index.html').read_text()
css=(root/'style.css').read_text()
domain='\n'.join(line for line in (root/'domain.mjs').read_text().replace('export function','function').splitlines() if not line.startswith('import '))
reportLogo=(root/'assets/report-logo.mjs').read_text().replace('export const','const')
pdfFonts=(root/'assets/report-fonts.mjs').read_text().replace('export const','const')
lifecycle=(root/'lifecycle-import.mjs').read_text().replace('export function','function')
lifecycle='\n'.join(line for line in lifecycle.splitlines() if not line.startswith('import '))
digest='\n'.join(line for line in (root/'digest.mjs').read_text().replace('export function','function').splitlines() if not line.startswith('import '))
controllers=(root/'controllers.mjs').read_text().replace('export function','function')
ownership=(root/'ownership.mjs').read_text().replace('export function','function')
searchable=(root/'searchable-select.mjs').read_text().replace('export function','function')
app='\n'.join(line for line in (root/'app.js').read_text().splitlines() if not line.startswith('import '))
cloud=(root/'cloud.mjs').read_text().replace('export function','function').replace('export class','class')
tracking=(root/'tracking-import.mjs').read_text().replace('export function','function')
tracking='\n'.join(line for line in tracking.splitlines() if not line.startswith('import '))
naming=(root/'nomenclature.mjs').read_text().replace('export function','function')
excel=(root/'excel.mjs').read_text().replace('export function','function').replace('const norm=', 'const excelNorm=').replace('norm(', 'excelNorm(')
html=html.replace('<script src="cloud-config.js"></script>','<script>'+((root/'cloud-config.js').read_text() if args.cloud else "window.VGP_CLOUD=Object.freeze({enabled:false,url:'',publicKey:'',workspaceId:''});")+ '</script>')
html=html.replace('<script src="vendor/excel.js"></script>','<script>'+(root/'vendor/excel.js').read_text()+'</script>')
html=html.replace('<link rel="stylesheet" href="style.css">','<style>'+css+'</style>')
html=html.replace('<script type="module" src="app.js"></script>','<script>'+pdfFonts+'\n'+reportLogo+'\n'+domain+'\n'+tracking+'\n'+naming+'\n'+cloud+'\n'+excel+'\n'+searchable+'\n'+ownership+'\n'+controllers+'\n'+lifecycle+'\n'+digest+'\n'+app+'</script>')
(root/'prototype-vgp.html').write_text(html)
